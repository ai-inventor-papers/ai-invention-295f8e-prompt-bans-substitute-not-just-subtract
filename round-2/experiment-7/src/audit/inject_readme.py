#!/usr/bin/env python3
"""Injects audit/readme_results.md (hand-written headline narrative) and results/summary.md (generated tables) into
README.md at the <!-- RESULTS --> marker (idempotent: replaces a previously injected block)."""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
readme = (ROOT / "README.md").read_text()
start, end = "<!-- RESULTS -->", "<!-- /RESULTS -->"
narr = (ROOT / "audit" / "readme_results.md").read_text() if (ROOT / "audit" / "readme_results.md").exists() else ""
summary = (ROOT / "results" / "summary.md").read_text()
block = f"{start}\n\n## Results\n\n{narr}\n\n## Result tables (generated by `src/report.py` from `results/`)\n\n{summary}\n\n{end}"
if end in readme:
    pre = readme.split(start)[0]
    post = readme.split(end)[1]
    readme = pre + block + post
else:
    readme = readme.replace(start, block)
(ROOT / "README.md").write_text(readme)
print("README updated", len(readme))
