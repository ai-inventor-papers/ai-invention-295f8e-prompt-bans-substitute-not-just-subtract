#!/usr/bin/env python3
"""results/summary.md: every K1 cell (shares, pass, Hill-1, pass cost, flips), the committed vs observed shares, the
K1 verdict lines, HR, locator, novelty audit and engine checks, rendered from the results files."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cfg8 import PRED_DIR, RESULTS_DIR, UNITS, read_json  # noqa: E402

ARM_NAME = {"A0": "twin T=1", "A1": "global T1.3 p.95", "A2": "global T1.6 p.95", "A3g": "global T2.0 p.95",
            "A4": "min-p .1 T3", "A5": "EDT T2>q90", "A6": "AdapT T2", "A7": "entropy-max @d2", "A8": "random pos @d2",
            "A9": "fork d1", "A10": "fork d2", "A11": "class-uniform force", "B1": "window 16 @T10-d2",
            "A9f": "filtered fork d1 (amendment)", "A10f": "filtered fork d2 (amendment)"}
ORDER = ["A0", "A1", "A2", "A3g", "A4", "A5", "A6", "A7", "A8", "A9", "A10", "A11", "A9f", "A10f", "B1"]


def f(x, nd=2):
    return "NA" if x is None else (f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def main() -> None:
    c1 = read_json(PRED_DIR / "commit1_dose_table.json")
    cells = read_json(RESULTS_DIR / "k1_cells.json")
    ver = read_json(RESULTS_DIR / "k1_verdict.json")
    L = ["# Summary tables (generated by src/report8.py)", ""]
    for u in ("T10", "B3", "B6", "A3", "G", "T1", "T2", "T03"):
        if u not in cells:
            continue
        e = c1["units"].get(u, {})
        cat = [c for c in UNITS[u]["catalogue"] if any(cells[u][a]["counts"].get(c) for a in cells[u])]
        L += [f"## {u}: {UNITS[u]['task']} ({UNITS[u]['model']}; role {e.get('role', UNITS[u]['role'])}"
              + (f"; d1 {e['dose']['d1']}, d2 {e['dose']['d2']}" if e.get("dose") else "") + ")", ""]
        L += ["| arm | n | " + " | ".join(cat) + " | other | invalid | pass | Hill-1 (correct, r25) | pass cost [95% CI] "
              "| decision changed | flips vs twin |", "|" + "---|" * (len(cat) + 9)]
        for a in ORDER:
            if a not in cells[u]:
                continue
            c = cells[u][a]
            sh = " | ".join(f(c["attempted"].get(k, 0)) for k in cat)
            ci = c["pass_cost_ci95"]
            L.append(f"| {a} {ARM_NAME.get(a, '')} | {c['n']} | {sh} | {f(c['attempted'].get('other', 0))} | "
                     f"{f(c['attempted'].get('invalid', 0))} | {f(c['pass_rate'])} | {f(c['hill1_correct_r25'])} | "
                     f"{f(c['pass_cost'])} [{f(ci[0])}, {f(ci[1])}] | {c['changed_decision']} | "
                     f"{c['label_flips_vs_twin']} |")
        if e.get("arms"):
            L += ["", "Committed composed prediction vs observed (attempted shares):", ""]
            for a in ("A9", "A10"):
                if a in cells[u]:
                    pr = e["arms"][a]["attempted"]
                    rp = e["arms"][a]["replay"]["attempted"]
                    ob = cells[u][a]["attempted"]
                    L.append(f"- {a} (T = {e['arms'][a]['T']}): " + "; ".join(
                        f"{k} pred {f(pr.get(k, 0))} / replay {f(rp.get(k, 0))} / obs {f(ob.get(k, 0))}"
                        for k in e["classes"] if max(pr.get(k, 0), ob.get(k, 0), rp.get(k, 0)) > 0.005)
                        + f"; predicted pass cost {f(e['arms'][a]['pass_cost'])}, observed {f(cells[u][a]['pass_cost'])}")
        L.append("")
    L += ["## K1 verdict", "", "```", __import__("json").dumps({k: v for k, v in ver.items() if k != "K1b"}, indent=1,
                                                               default=str)[:6000], "```", ""]
    (RESULTS_DIR / "summary.md").write_text("\n".join(L))
    print("summary.md written", len(L), "lines")


if __name__ == "__main__":
    main()
