#!/usr/bin/env python3
"""results/summary.md: every result table of claim L generated from results/*.json (no hand-typed numbers)."""

from __future__ import annotations

from cfg8 import RESULTS_DIR, TEMPS, UNITS, read_json


def f3(x) -> str:
    return "-" if x is None else f"{x:.3f}"


def main() -> None:
    an = read_json(RESULTS_DIR / "analysis_L.json")
    v = an["verdict"]
    L = ["# Claim L: results (generated by src/report8.py)", ""]
    L += [f"**Verdict: {v['status']}** - {v['n_pass']}/{v['n_scored']} scored units pass (MAE <= 0.10 and "
          f"H <= 0.3 bits); held-out {v['n_heldout_pass']}/{v['n_heldout_scored']}; held-out units with MAE > 0.2: "
          f"{v['n_heldout_mae_gt_0.2']}. Holm input (exact one-sided sign test, MAE_L < MAE_B0 over scored units): "
          f"p = {f3(v['holm_input_p_L_sign_test_vs_B0'])}.", ""]
    L += ["## Decision tokens (COMMIT #1)", "",
          "| unit | family | held-out | fit-twin counts | openings (d, tokens -> algorithm) | second decisions | "
          "H (bits) | boundary |", "|---|---|---|---|---|---|---|---|"]
    for u in an["units"]:
        loc = read_json(RESULTS_DIR / f"locate_{u}.json")
        ops = []
        sec = []
        for o in loc["openings"]:
            top = sorted(zip(o["mass_T1"], o["token_strs"], o["tokens"]), reverse=True)[:3]
            desc = ", ".join(f"{s!r} {m:.2f}->{o['classes']['class_of'][str(t)]}" for m, s, t in top)
            ops.append(f"{o['id']} d={o['d']}: {desc}")
            for t1, s in o.get("second", {}).items():
                if s.get("found"):
                    sec.append(f"{o['id']}/{t1}: d2={s['d2']} after {s['O2_str']!r}")
        L.append(f"| {u} | {UNITS[u]['family']} | {UNITS[u]['held_out']} | {loc['fit_counts']} | "
                 f"{'; '.join(ops) or '-'} | {'; '.join(sec) or '-'} | {f3(loc.get('H_unit_bits'))} | "
                 f"{loc['boundary']} |")
    L += ["", "## Law vs baselines (top-p 1, N = 100 per cell; MAE = mean TVD over T 0.3/0.7/1.0/1.3)", "",
          "| unit | MAE L | B0 flat | B1 tempering | B2 single-decision | BH entropy rival | replay-implied | "
          "pass |", "|---|---|---|---|---|---|---|---|"]
    for u, a in an["units"].items():
        m = a["mae"]["p1"]
        L.append(f"| {u} | {f3(m['L'])} | {f3(m['B0'])} | {f3(m['B1'])} | {f3(m['B2'])} | {f3(m['BH'])} | "
                 f"{f3(m['replay_implied'])} | {a['pass']} |")
    L += ["", "## Minority share per cell (predicted L / observed [Wilson 95%]; on-opening predicted; replay accuracy)",
          "", "| unit | minority | " + " | ".join(f"T {T}" for T in TEMPS) + " |", "|---|---|" + "---|" * len(TEMPS)]
    for u, a in an["units"].items():
        mi = a["minority"]
        if mi is None:
            continue
        j = a["bins"].index(mi)
        cells = []
        for T in TEMPS:
            c = a["cells"][f"p1|{T}"]
            r = a["replay"][f"p1|{T}"]
            cells.append(f"{c['pred']['L'][j]:.3f} / {c['shares'][j]:.2f} [{c['wilson'][mi][0]:.2f}, "
                         f"{c['wilson'][mi][1]:.2f}]; acc {f3(r['accuracy'])}")
        L.append(f"| {u} | {mi} | " + " | ".join(cells) + " |")
    L += ["", "## Drop T 1.0 -> 0.3 of the T-1 minority (paired slots, exact one-sided McNemar)", "",
          "| unit | observed drop | predicted drop | b:c | p | placebo reject rate |", "|---|---|---|---|---|---|"]
    for u, a in an["units"].items():
        d = a.get("drop")
        if d:
            L.append(f"| {u} | {d['obs_drop']:.2f} | {f3(d['pred_drop'])} | {d['mcnemar_b_c'][0]}:{d['mcnemar_b_c'][1]} "
                     f"| {d['p_one_sided']:.2g} | {d['placebo_temp_shuffle_reject_rate']:.3f} |")
    L += ["", "## Placebos and top-k", "",
          "| unit | T-permutation: true sum TVD / 5th pct / below | token-map shuffle: true MAE / placebo median / p | "
          "top-k 10 MAE L | H sweep-observed T 1 |", "|---|---|---|---|---|"]
    for u, a in an["units"].items():
        p = a.get("placebo_temperature_permutation") or {}
        t = a.get("placebo_token_map") or {}
        k = a["mae"].get("k10", {}).get("L")
        L.append(f"| {u} | {f3(p.get('true_sum_tvd'))} / {f3(p.get('p5'))} / {p.get('below_p5')} | "
                 f"{f3(t.get('true_mae'))} / {f3(t.get('placebo_mae_median'))} / {f3(t.get('p_le_true'))} | {f3(k)} | "
                 f"{f3(a.get('H_sweep_T1'))} |")
    L += ["", "## Ideas vs phrasings (1a-c): phrasing clusters per algorithm (AST 4-gram Jaccard 0.8) and correct-only "
          "Hill-1 (rarefied to 25)", "", "| unit | cell | clusters per algorithm (n programs) | Hill-1 correct | pass rate |",
          "|---|---|---|---|---|"]
    for u, a in an["units"].items():
        for s in ("p1", "k10"):
            for T in TEMPS:
                ph = a["phrasing"].get(f"{s}|{T}", {})
                desc = ", ".join(f"{alg} {d['phrasing_clusters_j08']} ({d['n']})" for alg, d in ph.items())
                c = a["cells"][f"{s}|{T}"]
                L.append(f"| {u} | {s} T {T} | {desc} | {f3(c['hill1_correct']['hill1'])} | {f3(c['pass_rate'])} |")
    b3 = an.get("b3_stream_lean")
    if b3:
        L += ["", f"B3 stream-lean test: {b3}"]
    bp = RESULTS_DIR / "base_subarm.json"
    if bp.exists():
        b = read_json(bp)
        L += ["", "## Base sub-arm (Qwen3-8B vs Qwen3-8B-Base, identical chat-templated ids)", "",
              "| task | margin instr (mean) | margin base | gain | gain template-free | phrasing dH [95% CI] | "
              "JS decision / phrasing / entropy-matched / random | URIAL ranks phrasing | entropy pctile base / instr |",
              "|---|---|---|---|---|---|---|---|---|"]
        for t, r in b["tasks"].items():
            L.append(f"| {t} | {sum(r['margin_instr']) / 5:.2f} | {sum(r['margin_base']) / 5:.2f} | "
                     f"{r['margin_gain_mean']:.2f} | {r['margin_gain_template_free_mean']:.2f} | "
                     f"{f3(r['phrasing_dH_mean'])} [{r['phrasing_dH_ci'][0]:.3f}, {r['phrasing_dH_ci'][1]:.3f}] | "
                     f"{f3(r['js_decision_mean'])} / {f3(r['js_phrasing_mean'])} / {f3(r['js_entropy_matched_mean'])} / "
                     f"{f3(r['js_random_positions_mean'])} | {r['urial_rank_phrasing']} | "
                     f"{f3(r['pctile_base_entropy_at_decision'])} / {f3(r['pctile_instr_entropy_at_decision'])} |")
        L += ["", f"Committed base-arm verdict: {b['verdict']}"]
    (RESULTS_DIR / "summary.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:12]))


if __name__ == "__main__":
    main()
