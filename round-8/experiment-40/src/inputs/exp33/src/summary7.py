def f(x, nd=2):
    if x is None:
        return "-"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, float):
        if abs(x) < 1e-3 and x != 0:
            return f"{x:.1e}"
        return f"{x:.{nd}f}"
    return str(x)


def J(name):
    p = results7(name)
    return read_json(p) if p.exists() else None


def main() -> None:
    L = ["# Iteration 7 result tables (generated by src/summary7.py)", ""]
    tasks = [t for t in ("T2", "T10", "T03") if results7(f"site_{t}.json").exists()]
    ec, ut = J("engine_check.json"), J("unit_tests_gpu.json")
    L += ["## Engine check and unit tests", ""]
    if ec:
        L += [f"- {t}: per-slot TWIN label agreement with exp30 {ec[t]['agree']}/{ec[t]['n']} "
              f"({f(ec[t]['share'])})" for t in ("T2", "T03", "T10") if t in ec] + [f"- Verdict: {ec['verdict']}"]
    if ut:
        L += [f"- U1 zero-rank edit bit-identical: {f(ut['U1_zero_rank_identical'])}; U2 full exchange at all blocks "
              f"reproduces the source (max |dlogit| {f(ut['U2_full_exchange_all_blocks']['max_abs_logit_diff'])}); U5 "
              f"full-rank rotation = exchange ({ut['U5_fullrank_rotation_equals_exchange']['identical_token_streams_of_10']}"
              f"/10 identical streams); U6 CRN determinism {ut['U6_crn_determinism']['identical_token_streams_of_10']}/10",
              f"- U3 packed vs separate forwards: max {f(ut['U3_packed_vs_separate']['max_program_diff'], 3)} nats per "
              f"program (mean {f(ut['U3_packed_vs_separate']['mean_program_diff'], 3)}); U4 cached vs full forward: "
              f"{f(ut['U4_cached_vs_full']['max_abs_contrast_diff'], 3)} nats (bf16 kernel-shape noise; see D-U3U4)",
              f"- U8 memory: peak {ut['U8_memory']['peak_GB_train_microbatch']} GB for a training micro-batch; U7a "
              f"gradient finite and non-zero: {f(ut['U7a_grad_finite_nonzero'])}", ""]
    L += ["## Site selection (layer profile + generation confirmation)", "",
          "| task | L* (TF) | single-block TF gain at L* | band 12-23 TF gain | ban: full@L* / band / base (of 30) | "
          "forced F3: full@L* / band / base | site |", "|---|---|---|---|---|---|---|"]
    for t in tasks:
        s = J(f"site_{t}.json")
        c = s["confirmation"]
        Lr = s["L_star"]
        Yc = c.get("forced_Y")
        fc = (f"{c[f'FULLF3_{Yc}_L{Lr}']['correct_Y']} / {c[f'FULLF3_{Yc}_band']['correct_Y']} / "
              f"{c[f'PADBASE_F3_{Yc}']['correct_Y']} ({Yc})") if Yc else "-"
        L.append(f"| {t} | {Lr} | {f(s['profile']['single_layer_gain'][str(Lr)] if str(Lr) in s['profile']['single_layer_gain'] else s['profile']['single_layer_gain'].get(Lr))} | "
                 f"{f(s['profile']['mean_gain']['band12-23'])} | {c[f'FULL_ban_L{Lr}']['correct_Y']} / "
                 f"{c['FULL_ban_band']['correct_Y']} / {c['BASE_W5']['correct_Y']} | {fc} | {s['site']} |")
    L.append("")
    p1 = J("p1.json")
    if p1:
        L += ["## P1: held-out generation recovery (amended LME_Y map, band 12-23, N = 30 per source)", ""]
        for t, r in p1["tasks"].items():
            L += [f"**{t}** (k* = {r['k_star']}; P1 evaluated at k = {r.get('P1_k')}): **{r.get('P1')}** "
                  f"{ {k: f(v) for k, v in (r.get('P1_clauses') or {}).items()} }", "",
                  "| source | Y | base | full-state | DAS k=1 | k=2 | k=4 | k=8 | k=16 | random k16 | permuted | pass base/full |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|"]
            for sname, ps in r["per_source"].items():
                d = ps["das"]

                def cc(k):
                    e = d.get(str(k)) or d.get(k)
                    return f"{e['count']} (p{f(e['pass'])})" if e else "-"
                rnd = ", ".join(f"{v['count']}" for a, v in ps["rand"].items() if "k16" in a)
                pm = ", ".join(f"{a.split('_')[0]}{a.rsplit('_', 1)[1]}: {v['count']}" for a, v in ps["perm"].items())
                L.append(f"| {sname} | {'+'.join(ps['Y'])} | {ps['base_count']} | {ps['full_count']} | {cc(1)} | {cc(2)} | "
                         f"{cc(4)} | {cc(8)} | {cc(16)} | {rnd} | {pm} | {f(ps['base_pass'])}/{f(ps['full_pass'])} |")
            L += ["", "| k | pooled recovery [slot bootstrap 95%] | random recovery | McNemar DAS vs random b:c (p) | "
                      "permuted transfer (max) | min pass ratio |", "|---|---|---|---|---|---|"]
            for k in RANKS:
                e = r["per_k"].get(str(k)) or r["per_k"].get(k)
                if not e:
                    continue
                ci = e.get("recovery_ci") or [None, None]
                mc = e.get("mcnemar_das_vs_rand")
                L.append(f"| {k} | {f(e['recovery'])} [{f(ci[0])}, {f(ci[1])}] | {f(e.get('random_recovery'))} | "
                         f"{(str(mc['b_das_only']) + ':' + str(mc['c_rand_only']) + ' (' + f(mc['p'], 4) + ')') if mc else '-'} | "
                         f"{f(e.get('permuted_transfer_max'))} | {f(e.get('pass_ratio_min'))} |")
            iia = r.get("slot_iia_ban") or {}
            L += ["", f"Slot IIA (ban source; label equal to the full ban prompt's label on the slot): "
                      f"{ {k: f(v) for k, v in iia.items()} }", ""]
        L += [f"**P1 overall: {p1['overall']}** ({p1['n_pass']} task(s) pass; Holm-adjusted McNemar p: "
              f"{ {k: f(v, 4) for k, v in p1['holm'].items()} })", ""]
    for t in tasks:
        c = J(f"p1_controls_{t}.json")
        if not c:
            continue
        L += [f"### Controls {t}", "", "| arm | correct-Y / off-default count | base | transfer | pass |", "|---|---|---|---|---|"]
        for arm, e in c.items():
            if not e:
                continue
            if "off_default_count" in e:
                L.append(f"| {arm} | {e['off_default_count']} (off-default) | {e['base_off_default']} | "
                         f"{f(e['off_default_transfer'])} | {f(e['pass'])} |")
            elif "transfer" in e:
                L.append(f"| {arm} | {e['count']} | {e['base']} | {f(e['transfer'])} | {f(e['pass'])} |")
            else:
                L.append(f"| {arm} (N = 10) | {e['count']} | - | - | {f(e['pass'])} |")
        L.append("")
    cr = J("c_routing.json")
    if cr:
        L += ["## C: routing of forced sources (correct Y / correct off-default) [Clopper-Pearson 95%]", "",
              "| task | forced Y | full-state | DAS k1 | k4 | k16 | landing under full-state | landing at k16 |",
              "|---|---|---|---|---|---|---|---|"]
        for t, r in cr["per_task"].items():
            for Y, e in r["per_Y"].items():
                def rr(k):
                    x = e.get(k) or {}
                    if x.get("routing") is None:
                        return "-"
                    ci = x.get("routing_ci") or [None, None]
                    return f"{f(x['routing'])} ({x['correct_Y']}/{x['correct_off_default']}) [{f(ci[0])}, {f(ci[1])}]"
                L.append(f"| {t} | {Y} | {rr('full')} | {rr('k1')} | {rr('k4')} | {rr('k16')} | "
                         f"{(e.get('full') or {}).get('landing')} | {(e.get('k16') or {}).get('landing')} |")
        L += ["", f"**C verdict: {cr['verdict']['verdict']}** (categorical tasks {cr['verdict']['categorical_tasks']}; "
                  f"margin-and-ladder by task {cr['verdict']['margin_and_ladder_by_task']})", ""]
    pil = J("committed_map_pilot.json")
    if pil:
        L += ["## Committed contrastive map (MAIN), 10-slot generation pilot", "",
              "| task | arm | correct Y (base) | pass (base) | labels | mean new tokens | finish |", "|---|---|---|---|---|---|---|"]
        for t, d in pil.items():
            for a, e in d.items():
                L.append(f"| {t} | {a} | {e['correct_Y']} ({e['base_correct_Y']}) | {f(e['pass'])} ({f(e['base_pass'])}) | "
                         f"{e['labels']} | {f(e['mean_new_tokens'], 0)} | {e['finish']} |")
        L.append("")
    for t in tasks:
        for nm in (f"das_fits_{t}.json", f"das_fits_ly_{t}.json"):
            d = J(nm)
            if not d:
                continue
            L += [f"### Fits {nm[:-5]}", "", "| fit | steps run (budget) | best step | best validation gain | k16 val gain (last) | "
                                             "orthonormality error | seconds |", "|---|---|---|---|---|---|---|"]
            for fit, x in d["fits"].items():
                if not x:
                    continue
                last = (x.get("val") or [{}])[-1].get("gain_by_k", {})
                L.append(f"| {fit} | {x.get('steps_run')} ({x.get('budget')}) | {x.get('best_step')} | {f(x.get('best_val'))} | "
                         f"{f(last.get('16') if '16' in last else last.get(16))} | {f(x.get('orth_err'), 6)} | {x.get('seconds')} |")
            L.append("")
    for t in tasks:
        for nm in (f"tf_eval_{t}_LY.json", f"tf_eval_{t}.json"):
            d = J(nm)
            if not d:
                continue
            L += [f"### Held-out teacher-forced evaluation {nm[:-5]}", "",
                  "| pairs | edit | n | mean gain | full-state gain | TF recovery | dLME_Y | dLME_D |", "|---|---|---|---|---|---|---|---|"]
            for kind, dd in d["summary"].items():
                for e, v in dd.items():
                    if any(e.startswith(x) for x in ("RAND2", "RAND3")):
                        continue
                    L.append(f"| {kind} | {e} | {v['n']} | {f(v['mean_gain'])} | {f(v['mean_full_gain'])} | "
                             f"{f(v['tf_recovery'])} | {f(v['d_lmeY'])} | {f(v['d_lmeD'])} |")
            L.append("")
    dm = J("dormant.json")
    if dm:
        L += ["## Dormant-subspace checks (c6)", "", "| task | k | natural variance share | random mean | percentile vs 1,000 "
              "random | top-k PCA (upper) | twin-only share | held-out displacement share (random k/4096) | projected-map TF "
              "retention |", "|---|---|---|---|---|---|---|---|---|"]
        for t, d in dm.items():
            for k, e in d["by_k"].items():
                L.append(f"| {t} | {k} | {f(e['natural_share'], 4)} | {f(e['random_mean'], 4)} | {f(e['percentile_vs_random'], 1)} | "
                         f"{f(e['pca_upper'], 3)} | {f(e['twin_only_share'], 4)} | {f(e['displacement_share_heldout'], 4)} "
                         f"({f(e['displacement_share_random_expect'], 4)}) | {f(e['projected_tf_retention'])} |")
        for t, d in dm.items():
            L.append(f"- {t}: reverse interchange {d.get('reverse')}; reverse recovery {f(d.get('reverse_recovery'))}; "
                     f"DORMANT FLAG {f(d.get('DORMANT_FLAG'))}")
        L.append("")
    for nm, lab in (("randinit_ly_T2.json", "amended LME_Y objective (matched to the evaluated map)"),
                    ("randinit_T2.json", "committed contrastive objective")):
        ri = J(nm)
        if ri:
            L += [f"## Sutter random-initialisation control (T2), {lab}", "",
                  f"- random network: held-out TF contrast gain of the fitted rank-16 map "
                  f"{f(ri['random_net_heldout_das16_gain'])} nats (full-state exchange on the random network "
                  f"{f(ri['random_net_heldout_full_gain'])}); trained network {f(ri['trained_heldout_das16_gain'])}; ratio "
                  f"{f(ri['ratio'])}; c3 (< 0.5) {f(ri['c3_pass_lt_0.5'])}"
                  + (f"; LME_Y gain random {f(ri.get('random_net_heldout_das16_lmeY_gain'))} vs trained "
                     f"{f(ri.get('trained_heldout_das16_lmeY_gain'))} (ratio {f(ri.get('ratio_lmeY'))})"
                     if ri.get("random_net_heldout_das16_lmeY_gain") is not None else ""), ""]
    mg = J("m_behaviour.json")
    if mg:
        L += ["## M behaviour (extension): what T2 writes under the prompts M places (N = 30, CRN slots 0-29)", "",
              "| prompt | pass | correct composition | correct off-default [CP 95%] | truncated |", "|---|---|---|---|---|"]
        for k, e in mg.items():
            ci = e.get("off_default_ci") or [None, None]
            L.append(f"| {k} | {f(e['pass'])} | {e['correct_composition']} | {e['correct_off_default']} "
                     f"[{f(ci[0])}, {f(ci[1])}] | {e['n_truncated']} |")
        L.append("")
    s2 = J("seed2_summary.json")
    if s2:
        L += ["## Second DAS init seed (T2, extension)", "",
              f"- principal angles between the seed-1 and seed-2 subspaces (degrees): "
              f"{ {k: [round(x, 1) for x in v] for k, v in s2['principal_angles_deg'].items()} }", "",
              "| arm | seed 1 | seed 2 | discordant s1-only : s2-only (p) | pass seed 2 |", "|---|---|---|---|---|"]
        for a, e in s2["cells"].items():
            d = e.get("discordant_s1only_s2only")
            L.append(f"| {a} | {e['seed1_count']} | {e['seed2_count']} | "
                     f"{(str(d[0]) + ':' + str(d[1]) + ' (' + f(e['mcnemar_p'], 3) + ')') if d else '-'} | {f(e['pass_seed2'])} |")
        L.append("")
    m = J("m_manifold.json")
    if m:
        L += ["## M: manifold placement in R_16 coordinates (T2)", "",
              f"- paraphrase null (n {m['paraphrase_null']['n']}): median D {f(m['paraphrase_null']['D_median'])}, 95th "
              f"percentile {f(m['paraphrase_null']['D_95'])}; MDS stress-1 {f(m['mds_stress1'], 3)}; runner-up "
              f"{m['runner_up']}", "", "| prompt | D to default centroid | null percentile | inside null 95% | coordinate "
                                       "along runner-up axis |", "|---|---|---|---|---|"]
        for k, e in m["probes"].items():
            L.append(f"| {k} | {f(e['D'])} | {f(e['null_percentile'], 1)} | {f(e['inside_null_95'])} | "
                     f"{f(e['coord_along_runnerup'])} |")
        L += ["", f"Centroid coordinates along the runner-up axis: { {k: f(v) for k, v in m['centroid_coord_along_runnerup'].items()} }",
              f"Implemented counts: {m['implemented_counts']}", ""]
        for kk, g in m["geodesic"].items():
            L.append(f"- kNN {kk}: leave-one-survivor bans, mean survivor rank {f(g['mean_survivor_rank'])} of 5 "
                     f"(random relabelling p {f(g['p_rank_le_observed'])}); unreachable pairs {g['n_unreachable']}")
            L.append(f"  - geodesic centroid table: { {a: {b: f(v) for b, v in row.items()} for a, row in g['centroid_geodesic_table'].items()} }")
        L.append("")
    rr = J("r_discreteness.json")
    if rr:
        hy = J("r_hybrids.json") or {}
        L += ["## R: discreteness of the plan coordinate (T2, lambda sweep, N = 20 each)", "",
              "| lambda | correct Y | correct default | pass | labels |", "|---|---|---|---|---|"]
        for lam, e in sorted(rr["curve"].items(), key=lambda x: float(x[0])):
            L.append(f"| {lam} | {e['correct_Y']} | {e['correct_default']} | {f(e['pass'])} | {e['labels']} |")
        L += ["", f"- logistic fit: lam0 {f(rr['fit']['lam0'])}, s {f(rr['fit']['s'], 3)}, width (10-90%) "
                  f"{f(rr['fit']['width_10_90'])}; hybrid candidates {len(rr['hybrid_candidates'])}, judged hybrids "
                  f"{hy.get('n_hybrid')} of {hy.get('n_correct_0.2_1.0')} correct programs; DISCRETE {f(hy.get('DISCRETE'))}", ""]
    nv = J("novelty_audit.json")
    if nv:
        L += ["## Novelty audit", "", f"- {nv['n_correct_other']} correct 'other' programs; classes {nv['classes']}; cost USD "
                                      f"{nv['cost_usd']}", ""]
    cells = J("cells.json")
    if cells:
        L += ["## Every generation cell (labels of correct programs)", "", "| task | arm | n | pass | truncated | correct composition |",
              "|---|---|---|---|---|---|"]
        for t, rows in cells.items():
            for r in rows:
                L.append(f"| {t} | {r['arm']} | {r['n']} | {f(r['pass'])} | {r['n_length']} | {r['correct_composition']} |")
        L.append("")
    (ROOT / "results" / "summary.md").write_text("\n".join(L) + "\n")
    print(f"summary.md: {len(L)} lines")


if __name__ == "__main__":
    main()
