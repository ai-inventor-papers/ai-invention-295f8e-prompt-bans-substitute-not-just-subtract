#!/bin/bash
# Restore everything the manifest marks `delete` (and the model weights, which live in the shared Hugging Face cache).
set -euo pipefail
cd "$(dirname "$0")"
uv venv .venv --python=3.12
uv pip install --python .venv/bin/python -r pyproject.toml
.venv/bin/python -m compileall -q src audit inputs/exp11/bench inputs/exp8/suite || true
# model weights (gated: accept the Gemma licence on huggingface.co and export HF_TOKEN first)
.venv/bin/huggingface-cli download google/gemma-3-4b-it --revision 093f9f388b31de276ce2de164bdc2081324b9767
.venv/bin/huggingface-cli download google/gemma-3-4b-pt --revision cc012e0a6d0787b4adcc0fa2c4da74402494554d
# the activation cache (cache/) is regenerated by the stage-1 runs: .venv/bin/python src/gen.py stage1_it / stage1_pt
